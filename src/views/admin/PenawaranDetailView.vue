function confirmImport() {
  if (!store.selectedData) return
  if (!store.selectedData.items) store.selectedData.items = []

  const validRows = importRows.value.filter(r => r._status !== 'error')
  if (validRows.length === 0) {
    toast.error('Tidak ada baris yang valid untuk diimport')
    return
  }

  validRows.forEach(row => {
    const pct = (Number(row.pajak_persen) || 11) / 100
    let baseHargaSatuan = Number(row.harga_satuan) || 0
    if (row.pajak_type === 'termasuk_pajak') {
      baseHargaSatuan = baseHargaSatuan / (1 + pct)
    }

    store.selectedData!.items.push({
      id: 0,
      part_id: row.jenis_item === 'barang' ? row.matched_part_id : null,
      jenis_item: row.jenis_item,
      pajak_type: row.pajak_type,
      pajak_persen: row.pajak_persen,
      nama_item: row.nama_item,
      deskripsi: row.deskripsi,
      qty: row.qty,
      harga_satuan: baseHargaSatuan,
      total_harga: row.qty * baseHargaSatuan
    })
  })

  recalculateTotal('items')
  toast.success(`${validRows.length} item berhasil diimport`)
  closeImportModal()
}

function recalculateTotal(source?: string) {
  if (!store.selectedData) return
  let sub = 0
  let autoTax = 0
  let hasTaxItem = false
  if (store.selectedData.items) {
    store.selectedData.items.forEach(it => {
      it.total_harga = it.qty * it.harga_satuan
      sub += it.total_harga
      if (it.pajak_type === 'dengan_pajak' || it.pajak_type === 'termasuk_pajak') {
        hasTaxItem = true
      }
    })
  }
  store.selectedData.subtotal = sub

  const diskon = Number(store.selectedData.diskon) || 0
  const afterDiskon = sub - diskon

  if (hasTaxItem) {
    // Recalculate tax from discounted subtotal
    let taxTotal = 0
    store.selectedData.items?.forEach(it => {
      if (it.pajak_type === 'dengan_pajak' || it.pajak_type === 'termasuk_pajak') {
        const pct = (Number((it as any).pajak_persen) || 11) / 100
        // Apply proportional discount to each item's contribution
        const itemRatio = sub > 0 ? (it.qty * it.harga_satuan) / sub : 0
        const itemAfterDiskon = (it.qty * it.harga_satuan) - (diskon * itemRatio)
        taxTotal += itemAfterDiskon * pct
      }
    })
    autoTax = taxTotal
    if (source === 'items' || source === 'diskon') {
      store.selectedData.pajak = autoTax
    }
  }

  store.selectedData.total_harga = afterDiskon + Number(store.selectedData.pajak)
}


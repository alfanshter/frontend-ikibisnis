function onPartSelected() {
  if (itemForm.value.jenis_item !== 'barang') return
  const p = parts.value.find(x => x.id === itemForm.value.part_id)
  if (p) {
    itemForm.value.nama_item = p.nama
    itemForm.value.harga_modal = getPartCost(p)
    applyPricingFromModal()
  }
}

function getPartCost(part: PartResponse) {
  const primary = part.suppliers?.find(s => s.isPrimary)
  if (primary) return Number(primary.harga) || 0
  const first = part.suppliers?.[0]
  return Number(first?.harga || 0)
}

function applyPricingFromModal() {
  if (itemForm.value.jenis_item === 'jasa') return
  if (itemForm.value.markup_mode === 'custom') return

  const modal = Math.max(0, Number(itemForm.value.harga_modal) || 0)

  if (itemForm.value.markup_mode === 'manual') {
    const upNominal = Math.max(0, Number(itemForm.value.markup_nominal) || 0)
    itemForm.value.harga_satuan = modal + upNominal
    return
  }

  if (itemForm.value.markup_mode === 'gpm') {
    const gpm = Math.min(99.99, Math.max(0, Number(itemForm.value.gpm_persen) || 0))
    if (gpm >= 100) return
    const beforeRound = modal / (1 - gpm / 100)
    let selling = beforeRound
    if (itemForm.value.is_round_up) {
      const step = Math.max(1, Number(itemForm.value.round_to) || 1)
      selling = Math.ceil(beforeRound / step) * step
    }
    itemForm.value.harga_satuan = Math.round(selling)
    return
  }

  const upPersen = Math.max(0, Number(itemForm.value.markup_persen) || 0)
  const beforeRound = modal + (modal * upPersen / 100)
  let selling = beforeRound

  if (itemForm.value.is_round_up) {
    const step = Math.max(1, Number(itemForm.value.round_to) || 1)
    selling = Math.ceil(beforeRound / step) * step
  }

  itemForm.value.harga_satuan = Math.round(selling)
}

function selectPart(part: PartResponse | null) {
  if (!part) {
    itemForm.value.part_id = null
    partSearchText.value = ''
    showPartDropdown.value = false
    return
  }
  itemForm.value.part_id = part.id
  partSearchText.value = `${part.sku} - ${part.nama}`
  showPartDropdown.value = false
  onPartSelected()
}

function onPartBlur() {
  setTimeout(() => {
    showPartDropdown.value = false
    if (!partSearchText.value.trim()) {
      itemForm.value.part_id = null
      return
    }

    const exact = parts.value.find(p => `${p.sku} - ${p.nama}`.toLowerCase() === partSearchText.value.trim().toLowerCase())
    if (exact) {
      selectPart(exact)
      return
    }

    if (itemForm.value.part_id) {
      const selected = parts.value.find(p => p.id === itemForm.value.part_id)
      partSearchText.value = selected ? `${selected.sku} - ${selected.nama}` : ''
    } else {
      partSearchText.value = ''
    }
  }, 150)
}


function loadPdfSettings() {
  if (typeof window === 'undefined') return
  const raw = window.localStorage.getItem('ikibisnis_penawaran_pdf_settings')
  if (!raw) return
  try {
    pdfSettings.value = { ...defaultPdfSettings, ...JSON.parse(raw) }
  } catch {
    pdfSettings.value = { ...defaultPdfSettings }
  }
}

function savePdfSettings() {
  if (typeof window === 'undefined') return
  window.localStorage.setItem('ikibisnis_penawaran_pdf_settings', JSON.stringify(pdfSettings.value))
}

function getPdfPageFormat(size: string) {
  switch (size) {
    case 'Letter': return 'letter'
    case 'Legal': return 'legal'
    default: return 'a4'
  }
}

function normalizePdfImageData(dataUrl: string, mimeType: 'image/png' = 'image/png') {
  if (!dataUrl || !dataUrl.startsWith('data:image/')) return ''

  const image = new Image()
  image.src = dataUrl

  return new Promise<string>((resolve) => {
    image.onload = () => {
      const canvas = document.createElement('canvas')
      canvas.width = image.naturalWidth || image.width
      canvas.height = image.naturalHeight || image.height
      const ctx = canvas.getContext('2d')
      if (!ctx) {
        resolve(dataUrl)
        return
      }
      ctx.clearRect(0, 0, canvas.width, canvas.height)
      ctx.drawImage(image, 0, 0)
      resolve(canvas.toDataURL(mimeType))
    }
    image.onerror = () => resolve(dataUrl)
  })
}

async function handlePdfImageUpload(event: Event, key: 'headerImage' | 'footerImage' | 'watermarkImage' | 'signatureImage') {
  const input = event.target as HTMLInputElement
  const file = input.files?.[0]
  if (!file) return

  const reader = new FileReader()
  reader.onload = async () => {
    const result = String(reader.result || '')
    const normalized = await normalizePdfImageData(result)
    pdfSettings.value[key] = normalized
    savePdfSettings()
  }
  reader.readAsDataURL(file)
  input.value = ''
}

function addPdfImage(doc: jsPDF, imageData: string, x: number, y: number, width: number, height: number, opacity = 1) {
  if (!imageData) return

  try {
    let format: 'PNG' | 'JPEG' = 'PNG'
    if (imageData.startsWith('data:image/jpeg')) format = 'JPEG'
    if (imageData.startsWith('data:image/jpg')) format = 'JPEG'

    if (opacity < 1 && 'GState' in doc) {
      const gState = new (doc as any).GState({ opacity })
      doc.setGState(gState)
      doc.addImage(imageData, format, x, y, width, height)
      doc.setGState(new (doc as any).GState({ opacity: 1 }))
      return
    }
    doc.addImage(imageData, format, x, y, width, height)
  } catch {
    // Ignore invalid image data silently
  }
}

function addPdfImageContain(
  doc: jsPDF,
  imageData: string,
  x: number,
  y: number,
  width: number,
  height: number,
  opacity = 1
) {
  if (!imageData) return

  try {
    const properties = doc.getImageProperties(imageData)
    const imageRatio = properties.width / properties.height
    const areaRatio = width / height
    const renderWidth = imageRatio >= areaRatio ? width : height * imageRatio
    const renderHeight = imageRatio >= areaRatio ? width / imageRatio : height
    const imageX = x + ((width - renderWidth) / 2)
    const imageY = y + ((height - renderHeight) / 2)

    addPdfImage(doc, imageData, imageX, imageY, renderWidth, renderHeight, opacity)
  } catch {
    addPdfImage(doc, imageData, x, y, width, height, opacity)
  }
}

function addPdfImageCover(
  doc: jsPDF,
  imageData: string,
  x: number,
  y: number,
  width: number,
  height: number
) {
  if (!imageData) return

  try {
    const properties = doc.getImageProperties(imageData)
    const imageRatio = properties.width / properties.height
    const areaRatio = width / height
    const renderWidth = imageRatio >= areaRatio ? height * imageRatio : width
    const renderHeight = imageRatio >= areaRatio ? height : width / imageRatio
    const imageX = x + ((width - renderWidth) / 2)
    const imageY = y + ((height - renderHeight) / 2)

    doc.saveGraphicsState()
    doc.rect(x, y, width, height)
    doc.clip()
    addPdfImage(doc, imageData, imageX, imageY, renderWidth, renderHeight)
    doc.restoreGraphicsState()
  } catch {
    addPdfImage(doc, imageData, x, y, width, height)
  }
}

function getPdfHeaderHeight(settings: any) {
  if (settings.showHeaderImage && settings.headerImage) {
    return Math.max(18, Number(settings.headerImageHeight) || 32)
  }

  return 18
}

function getPdfFooterHeight(doc: jsPDF, settings: any, pageWidth: number) {
  const configuredHeight = Math.max(12, Number(settings.footerImageHeight) || 20)
  if (settings.showFooterImage && settings.footerImage) {
    try {
      const properties = doc.getImageProperties(settings.footerImage)
      const proportionalHeight = pageWidth * (properties.height / properties.width)
      return Math.max(configuredHeight, Math.min(80, proportionalHeight))
    } catch {
      return configuredHeight
    }
  }

  return 12
}

function drawPdfHeader(doc: jsPDF, settings: any, pageWidth: number, left: number, right: number, top: number) {
  if (!settings.showHeader) return

  const bandHeight = getPdfHeaderHeight(settings)
  const bandTop = 0
  const contentLeft = left
  const contentRight = pageWidth - right

  if (settings.showHeaderImage && settings.headerImage) {
    doc.setFillColor(255, 255, 255)
    doc.rect(0, bandTop, pageWidth, bandHeight, 'F')
    addPdfImageCover(doc, settings.headerImage, 0, bandTop, pageWidth, bandHeight)
  } else {
    doc.setFillColor(247, 247, 247)
    doc.rect(0, bandTop, pageWidth, bandHeight, 'F')
    doc.setTextColor(20, 20, 20)
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(16)
    doc.text(settings.headerTitle || 'Penawaran Harga', contentLeft, bandTop + 7)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    doc.text(settings.headerSubtitle || 'PT Ikibisnis', contentLeft, bandTop + 13)
  }

  doc.setDrawColor(220, 220, 220)
  doc.line(contentLeft, bandHeight, contentRight, bandHeight)
}

function drawPdfFooter(doc: jsPDF, settings: any, pageWidth: number, pageHeight: number, left: number, right: number) {
  if (!settings.showFooter) return

  const bandHeight = getPdfFooterHeight(doc, settings, pageWidth)
  const footerY = pageHeight - Math.min(4, bandHeight / 2)
  const bandTop = pageHeight - bandHeight
  const contentLeft = left
  const contentRight = pageWidth - right

  if (settings.showFooterImage && settings.footerImage) {
    doc.setFillColor(255, 255, 255)
    doc.rect(0, bandTop, pageWidth, bandHeight, 'F')
    addPdfImageContain(doc, settings.footerImage, 0, bandTop, pageWidth, bandHeight)
  } else {
    doc.setFillColor(247, 247, 247)
    doc.rect(0, bandTop, pageWidth, bandHeight, 'F')
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(8)
    doc.setTextColor(90, 90, 90)
    doc.text(settings.footerText || 'Generated by Ikibisnis', contentLeft, footerY)
    doc.text(`Halaman ${doc.getCurrentPageInfo().pageNumber}`, contentRight, footerY, { align: 'right' })
  }

  doc.setDrawColor(220, 220, 220)
  doc.line(contentLeft, bandTop, contentRight, bandTop)
}

function drawPdfWatermark(doc: jsPDF, settings: any, pageWidth: number, pageHeight: number) {
  if (!settings.showWatermark) return

  if (settings.showWatermarkImage && settings.watermarkImage) {
    const watermarkWidth = pageWidth * 0.68
    const watermarkHeight = pageHeight * 0.45
    addPdfImageContain(
      doc,
      settings.watermarkImage,
      (pageWidth - watermarkWidth) / 2,
      (pageHeight - watermarkHeight) / 2,
      watermarkWidth,
      watermarkHeight,
      0.1
    )
    return
  }

  doc.setTextColor(225, 225, 225)
  doc.setFontSize(34)
  doc.setFont('helvetica', 'bold')
  doc.text(settings.watermarkText || 'DRAFT', pageWidth / 2, pageHeight / 2, {
    align: 'center',
    angle: 45
  })
}

function drawPdfSectionHeading(doc: jsPDF, title: string, x: number, y: number, width: number) {
  doc.setFillColor(241, 245, 249)
  doc.roundedRect(x, y, width, 7, 1.5, 1.5, 'F')
  doc.setTextColor(42, 52, 64)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(9)
  doc.text(title, x + 3, y + 4.7)
}

function ensurePdfSectionSpace(
  doc: jsPDF,
  settings: any,
  currentY: number,
  requiredHeight: number,
  pageWidth: number,
  pageHeight: number,
  left: number,
  right: number,
  top: number,
  bottom: number
) {
  const footerHeight = settings.showFooter ? getPdfFooterHeight(doc, settings, pageWidth) : 0
  const contentBottom = Math.max(bottom, footerHeight + 4)
  if (currentY + requiredHeight <= pageHeight - contentBottom) return currentY

  doc.addPage()
  drawPdfWatermark(doc, settings, pageWidth, pageHeight)
  drawPdfHeader(doc, settings, pageWidth, left, right, top)
  drawPdfFooter(doc, settings, pageWidth, pageHeight, left, right)
  return settings.showHeader ? getPdfHeaderHeight(settings) + 8 : top
}


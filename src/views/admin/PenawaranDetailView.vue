  const harga = Number(itemForm.value.harga_satuan) || 0
  const type = itemForm.value.pajak_type
  const pct = (Number(itemForm.value.pajak_persen) || 0) / 100

  if (type === 'tanpa_pajak') {
    const total = qty * harga
    return { dpp: total, ppn: 0, total, type, pct: itemForm.value.pajak_persen }
  } else if (type === 'dengan_pajak') {
    const dpp = qty * harga
    const ppn = dpp * pct
    return { dpp, ppn, total: dpp + ppn, type, pct: itemForm.value.pajak_persen }
  } else if (type === 'termasuk_pajak') {
    const totalBruto = qty * harga
    const dpp = totalBruto / (1 + pct)
    const ppn = totalBruto - dpp
    return { dpp, ppn, total: totalBruto, type, pct: itemForm.value.pajak_persen }
  }
  return { dpp: 0, ppn: 0, total: 0, type: 'tanpa_pajak', pct: itemForm.value.pajak_persen }
})
